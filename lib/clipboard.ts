/**
 * Copy with a fallback for in-app browsers.
 *
 * Telegram, WhatsApp and Instagram open links in webviews where
 * navigator.clipboard is missing or rejects even on HTTPS. The legacy
 * textarea + execCommand path still works there, so a failed or absent
 * Clipboard API falls through to it rather than failing silently.
 */
export async function copyText(value: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(value);
      return true;
    }
  } catch {
    /* fall through to the legacy path */
  }

  try {
    const ta = document.createElement("textarea");
    ta.value = value;
    ta.setAttribute("readonly", "");
    ta.style.position = "fixed";
    ta.style.top = "0";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.focus();
    ta.select();
    ta.setSelectionRange(0, value.length);
    const ok = document.execCommand("copy");
    document.body.removeChild(ta);
    return ok;
  } catch {
    return false;
  }
}
